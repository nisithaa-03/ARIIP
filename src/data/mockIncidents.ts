// Resolver that provides incidents for any city, state, or nationwide
export function resolveIncidentsForCity(
  cityName: string,
  stateName: string,
  isAllIndia: boolean,
  currentIncidents: Incident[]
): Incident[] {
  if (isAllIndia) {
    return currentIncidents;
  }

  // Filter current incidents matching city
  const cityMatches = currentIncidents.filter(
  (i) =>
    i.location?.city?.toLowerCase() === cityName.toLowerCase()
);

  if (cityMatches.length > 0) {
    return cityMatches;
  }

  // If none exist yet for this city, dynamically generate authentic Indian road hazards for it!
  const cityInfo = getCityByName(cityName) || {
    name: cityName,
    state: stateName,
    country: 'India',
    lat: 12.9716,
    lng: 77.5946,
    zoom: 12.8,
    municipalBody: `${cityName} Municipal Corporation`,
    areas: ['Center', 'Main Arterial', 'Station Road', 'Industrial Corridor'],
  };

  return generateIncidentsForCity(cityInfo);
}
